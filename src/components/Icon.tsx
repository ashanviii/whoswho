/** Named icon wrapper over lucide-react (the icon set shadcn/ui uses). */
import {
  ArrowLeft,
  BookOpen,
  Check,
  ChevronDown,
  ChevronRight,
  Download,
  ExternalLink,
  Eye,
  EyeOff,
  Globe,
  Info,
  List,
  LoaderCircle,
  Maximize2,
  Minimize2,
  Minus,
  Monitor,
  MoreHorizontal,
  Moon,
  Network,
  Plus,
  RefreshCw,
  Scan,
  Search,
  Shield,
  Shuffle,
  SlidersHorizontal,
  Sparkles,
  Sun,
  TriangleAlert,
  Users,
  X,
  type LucideIcon,
} from 'lucide-react';

const ICONS = {
  search: Search,
  x: X,
  plus: Plus,
  minus: Minus,
  fit: Scan,
  shuffle: Shuffle,
  sun: Sun,
  moon: Moon,
  monitor: Monitor,
  book: BookOpen,
  eye: Eye,
  eyeOff: EyeOff,
  filter: SlidersHorizontal,
  chevronDown: ChevronDown,
  chevronRight: ChevronRight,
  arrowLeft: ArrowLeft,
  refresh: RefreshCw,
  info: Info,
  graph: Network,
  list: List,
  download: Download,
  expand: Maximize2,
  shrink: Minimize2,
  external: ExternalLink,
  shield: Shield,
  check: Check,
  alert: TriangleAlert,
  globe: Globe,
  sparkle: Sparkles,
  users: Users,
  loader: LoaderCircle,
  more: MoreHorizontal,
} satisfies Record<string, LucideIcon>;

export type IconName = keyof typeof ICONS;

export function Icon({ name, size = 18, className = '', strokeWidth = 2 }: { name: IconName; size?: number; className?: string; strokeWidth?: number }) {
  const Cmp = ICONS[name];
  return <Cmp size={size} strokeWidth={strokeWidth} className={`shrink-0 ${className}`} aria-hidden="true" />;
}
